-- Average Pointer

SELECT AVG(pointer) AS Average_Pointer
FROM student;

-- Maximum Pointer

SELECT MAX(pointer) AS Max_Pointer
FROM student;

-- Minimum Pointer

SELECT MIN(pointer) AS Min_Pointer
FROM student;

-- Count Records

SELECT COUNT(pointer) AS Count_Pointer
FROM student;

-- Sum of Pointer

SELECT SUM(pointer) AS Total_Pointer
FROM student;